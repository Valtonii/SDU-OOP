/*
A value is the data. A variable is a named box you keep data in.

Then three facts:

A value can stand alone. Console.WriteLine(5); has a value and no box.
A box is never empty. Declare one without assigning and C# puts a zero in it.
The box's type decides what you're allowed to put in it.

And the bit worth remembering above all: boxes change, values don't.
x = 7 swaps what's in the box. It doesn't turn the number 5 into 7.
*/
